#!/usr/bin/env node
// Generate the Filament admin theme bundle the screenshot workbench needs at
// public/build/filament/theme.css together with a minimal Vite manifest entry.
//
// The in-repo workbench does not run a Vite build, but the admin panel still
// resolves its theme through Vite (`->viteTheme('resources/css/filament/admin/theme.css', 'build/filament')`).
// A Filament theme REPLACES the published app.css, so a stub theme file means
// every admin page renders with no panel CSS at all — the screenshot runner's
// stylesheet guard rightly aborts those captures. Build a real theme instead.

import { existsSync, mkdirSync, statSync, writeFileSync } from 'node:fs'
import { spawnSync } from 'node:child_process'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const sourcePath = join(
    repoRoot,
    'workbench',
    'resources',
    'css',
    'filament',
    'admin',
    'theme.css',
)
const testbenchAppRoot = join(
    repoRoot,
    'vendor',
    'orchestra',
    'testbench-core',
    'laravel',
)
const outputPath = join(
    testbenchAppRoot,
    'public',
    'build',
    'filament',
    'theme.css',
)
const manifestPath = join(
    testbenchAppRoot,
    'public',
    'build',
    'filament',
    'manifest.json',
)

function source(path) {
    return `@source "${path}";`
}

function buildSource() {
    const sources = [
        source(join(testbenchAppRoot, 'app', 'Filament', '**', '*')),
        source(
            join(testbenchAppRoot, 'resources', 'views', 'filament', '**', '*'),
        ),
        source(
            join(
                repoRoot,
                'packages',
                '*',
                'resources',
                'views',
                '**',
                '*.blade.php',
            ),
        ),
        source(
            join(
                repoRoot,
                'vendor',
                'capell-app',
                '*',
                'resources',
                'views',
                '**',
                '*.blade.php',
            ),
        ),
    ]

    const tailwindClassesPath = join(
        testbenchAppRoot,
        'storage',
        'capell',
        'tailwind-classes.txt',
    )

    if (existsSync(tailwindClassesPath)) {
        sources.push(source(tailwindClassesPath))
    }

    return [
        '/* GENERATED by scripts/screenshots/build-filament-theme-css.mjs — do not edit. */',
        `@import "${join(repoRoot, 'vendor', 'filament', 'filament', 'resources', 'css', 'theme.css')}";`,
        '@import "tailwindcss";',
        ...sources,
        '',
    ].join('\n')
}

mkdirSync(dirname(sourcePath), { recursive: true })
mkdirSync(dirname(outputPath), { recursive: true })
writeFileSync(sourcePath, buildSource())

const cli = join(repoRoot, 'node_modules', '.bin', 'tailwindcss')
const result = spawnSync(
    cli,
    ['--input', sourcePath, '--output', outputPath, '--minify'],
    {
        cwd: repoRoot,
        stdio: 'inherit',
    },
)

if (result.status !== 0) {
    console.error('Filament theme build failed.')
    process.exitCode = result.status ?? 1
} else {
    writeFileSync(
        manifestPath,
        `${JSON.stringify(
            {
                'resources/css/filament/admin/theme.css': {
                    file: 'theme.css',
                    src: 'resources/css/filament/admin/theme.css',
                    isEntry: true,
                },
            },
            null,
            2,
        )}\n`,
    )

    const kilobytes = Math.round(statSync(outputPath).size / 1024)
    console.log(`Built ${outputPath} (${kilobytes} KB).`)
    console.log(`Wrote ${manifestPath}.`)
}
